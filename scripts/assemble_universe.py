# Upstream names its gear sets by the phase they are BiS *for*: `preraid`
# before Karazhan, `p1` for T4 content, `p2` for T5. Pre-raid is phase 1 --
# it is the set you take into a phase-1 raid.
CURATED_SET_PHASE: dict[str, int] = {
    "preraid": 1,
    # Mage spells its pre-raid set `preBisArcane`, which the vendored name
    # lowercases to `prebis`. Same claim as `preraid`, different upstream
    # spelling.
    "prebis": 1,
    "p1": 1,
    "p2": 2,
    "p3": 3,
    "p4": 4,
    "p5": 5,
    # Warlock is the one spec whose upstream sets are named by raid TIER
    # rather than by phase, so without these rows every one of its labels
    # resolves to None, `bis_set_labels_for_max_phase` filters them all out,
    # and only `preraid` survives -- which is exactly what shipped before this
    # entry existed: warlock carried the same ten pre-raid items tagged BiS at
    # p2, p3, p4 AND p5, with its Sunwell set contributing nothing.
    #
    # The mapping is not a guess about release order. Median item level of
    # each warlock set, joined to db.json, against the same measure on
    # balance's phase-named ladder:
    #
    #     warlock  preraid 110  t4 115  t5 128  t6 146  za 146  swp 154
    #     balance  preraid 110  p1 115  p2 128  p3 143  p4 141  p5 154
    #
    # Each tier lands on its phase counterpart. `t6` and `za` are the same
    # power because `za` IS the t6 set with two Zul'Aman pieces swapped in
    # (they share 13 of 15 items), which is why za maps to the later phase
    # without implying it is stronger content.
    "t4": 1,
    "t5": 2,
    "t6": 3,
    "za": 4,
    "swp": 5,
}


def curated_set_phase(label: str) -> int | None:
    """The phase a curated set is BiS for, or None if unrecognised.

    `feral_p2_6p` / `p2_9p` are the same phase split by tier-bonus count, so
    the leading `pN` is the phase and the suffix is a variant. The same split
    reads a build prefix off warlock's `destro_fire_*` family and hunter's
    `bm`/`sv` sets, so the phase token is not always first -- try each
    underscore-separated token and take the first that names a phase.
    """
    for token in label.split("_"):
        phase = CURATED_SET_PHASE.get(token)
        if phase is not None:
            return phase
    return None


def bis_set_labels_for_max_phase(
    sets_by_item: dict[int, list[str]], max_phase: int
) -> dict[int, list[str]]:
    """Curated sets that still make a *current* BiS claim at `max_phase`.

    "BiS" is a claim about a phase, exactly as wowsims scopes it -- there is no
    absolute BiS. A set for an earlier phase says "this was BiS before the
    content you are now running", which is the opposite of a recommendation.
    Without this, a phase-5 ret list badged Justicar (T4) chest, boots and
    crown plus five pre-raid pieces as `BiS`, because the union flattened three
    phase sets into one verdict (carry-forward 47 §1).

    Where no set is vendored for `max_phase`, the newest available phase is
    used rather than tagging nothing: the claim degrades to "the latest curated
    set we vendor", which `curatedSets` then names and the HTML report warns
    about. Ret stops at `p3` upstream as of 5c7491899 (2026-08-13) and still
    degrades this way for p4/p5; feral cat runs to `p5` upstream, so a gap
    there means the phase is simply not vendored yet (see `TRACKED` in
    scripts/sync_wowsims.py) and is fixed by pinning it, not by widening this
    fallback.
    """
    known = {
        iid: [s for s in labels if curated_set_phase(s) is not None]
        for iid, labels in sets_by_item.items()
    }
    available = {
        phase
        for labels in known.values()
        for phase in (curated_set_phase(s) for s in labels)
        if phase is not None and phase <= max_phase
    }
    if not available:
        return {}
    target = max(available)
    scoped = {
        iid: sorted(s for s in labels if curated_set_phase(s) == target)
        for iid, labels in known.items()
    }
    return {iid: labels for iid, labels in scoped.items() if labels}


def wowsims_curated_sets_by_item(profile: SpecProfile) -> dict[int, list[str]]:
    """itemId -> the curated set names that equip it, sorted.

    Carried per item rather than flattened to one boolean because the set name
    is the whole provenance of the claim. A union says only "some upstream
    preset equipped this", which is what let Shapeshifter's Signet -- 25
    agility, 18 stamina, 20 expertise, no strength -- ship tagged a flat "BiS"
    on a retribution list (carry-forward 47 §1). Upstream really does equip it
    in all three ret sets, so the tag was not a cross-spec leak and not a bug
    in membership; the defect is that "BiS" asserts a per-item verdict the
    source never made. Naming the set lets the reader see it is a preset's
    choice, and lets `curatedSets` outrank a bare label downstream.
    """
    by_item: dict[int, list[str]] = {}
    for path in profile.gear_sets:
        if not path.is_file():
            continue
        doc = load_json(path)
        assert isinstance(doc, dict)
        # `ret_p2.gear.json` -> `p2`: the stem carries the spec prefix, which is
        # redundant once the row is in a spec's own universe file.
        label = path.stem.removesuffix(".gear")
        label = label.split("_", 1)[1] if "_" in label else label
        for item in doc.get("items") or []:
            if isinstance(item, dict) and item.get("id") is not None:
                by_item.setdefault(int(item["id"]), []).append(label)
    return {iid: sorted(set(names)) for iid, names in by_item.items()}


def eligible_d7(it: dict, profile: SpecProfile) -> bool:
    """D7 rules from PLAN.md / sub-phase 0 — not generate_pool.ret_equippable().

    Two different questions live here, and only one of them is ours:

    - *Can this class physically equip the item?* The fork already answers
      that, in `canEquipItem`. We look the answer up rather than re-deriving
      it — see `_equip_eligibility()` for why the re-derivation was deleted.
    - *Do we want it in an upgrade pool?* Quality floor, Kael's temporary
      legendaries, per-spec SME exclusions. These are our policy, the fork has
      no opinion on them, and they stay here.
    """
    if it["id"] in KAEL_TEMP_LEGENDARY_IDS:
        return False
    # Applied here rather than at any single admission route so that an
    # excluded id cannot re-enter through a different one.
    if int(it["id"]) in profile.exclude_ids:
        return False
    if int(it["id"]) not in profile.equip_eligible_ids:
        return False
    weapon_type = it.get("weaponType")
    if weapon_type and int(weapon_type) in profile.policy_excluded_weapon_types:
        return False
    # Scoped to weapons: an off-hand frill or a shield is not a "one-hander"
    # this rule is refusing on hand type, it is refused as a weapon type above
    # when a spec excludes it. Armor and trinkets carry no handType at all.
    if profile.policy_two_hand_only and weapon_type:
        if it.get("handType") != HAND_TYPE_TWO_HAND:
            return False
    t = it.get("type")
    if t is None:
        return False
    if ITEM_TYPE_SLOT.get(t) is None:
        return False
    return (it.get("quality") or 0) >= MIN_QUALITY


def item_stats(it: dict) -> list[float]:
    scaling = (it.get("scalingOptions") or {}).get("0") or {}
    raw_map = scaling.get("stats")
    if isinstance(raw_map, dict) and raw_map:
        out = [0.0] * 42
        for k, v in raw_map.items():
            i = int(k)
            if 0 <= i < len(out):
                out[i] = float(v)
        return out
    arr = it.get("stats") or []
    return [float(x) for x in arr]


def weapon_dps(it: dict) -> float:
    """Average weapon damage per second, upstream's formula.

    ui/core/proto_utils/equipped_item.ts getWeaponDPS:
    (weaponDamageMin + weaponDamageMax) / 2 / weaponSpeed. These live beside
    the stats map in scalingOptions, never inside it, so ep_score cannot see
    them without this.
    """
    scaling = (it.get("scalingOptions") or {}).get("0") or {}
    lo = float(scaling.get("weaponDamageMin") or 0.0)
    hi = float(scaling.get("weaponDamageMax") or 0.0)
    speed = float(it.get("weaponSpeed") or 0.0)
    if speed <= 0 or (lo <= 0 and hi <= 0):
        return 0.0
    return (lo + hi) / 2 / speed


def ep_score(
    stats: list[float],
    weights: dict[str, float],
    *,
    item: dict | None = None,
    slot: str | None = None,
    pseudo_weights: dict[str, float] | None = None,
) -> float:
    total = 0.0
    for k, w in weights.items():
        i = int(k)
        if i < len(stats):
            total += stats[i] * w
    # Weapon damage is the dominant term for a ret two-hander (seals,
    # judgements and Crusader Strike all scale off it) but is not a stat, so
    # a weapon scored on its stat line alone ranks near-arbitrarily -- Glaive
    # of the Pit scored 0.00, last of 17, on an empty stat map. Upstream
    # carries this as PseudoStatMainHandDps, weighted separately from the
    # stats array; ret's P2 preset prices it at 5.34.
    if item is not None and slot == "weapon" and pseudo_weights:
        mh = pseudo_weights.get(str(PSEUDO_MAIN_HAND_DPS))
        if mh:
            total += weapon_dps(item) * mh
    return total


# A member line, tolerating the option suffix protobuf allows
# (`Foo = 1 [deprecated = true];`). `ui.proto` already carries `deprecated` on
# message fields, so the syntax is live in a file this parses.
_ENUM_MEMBER_RE = re.compile(r"^\s+(\w+)\s*=\s*(-?\d+)\s*(?:\[[^\]]*\])?\s*;", re.M)
# Anything else that occupies a statement line inside an enum body. Everything
# not matched by either pattern is a member we failed to parse.
_ENUM_NON_MEMBER_RE = re.compile(
    r"^\s*(?://|/\*|\*|reserved\b|option\b|\}|$)", re.M
)


def _enum_members(proto_path: Path, enum_name: str) -> dict[int, str]:
    text = proto_path.read_text(encoding="utf-8")
    enum = re.search(rf"enum {enum_name} \{{(.*?)\n\}}", text, re.S)
    if not enum:
        raise SystemExit(f"could not find the {enum_name} enum in {proto_path}")
    body = enum.group(1)
    members = _ENUM_MEMBER_RE.findall(body)
    if not members:
        raise SystemExit(f"{enum_name} enum in {proto_path} has no members")

    # A partial parse is the actual defect: dropping one member of RepLevel or
    # Profession has no downstream assertion to catch it, and surfaces as a bare
    # number in a display field (ticket 66). Refuse to guess.
    for line in body.splitlines():
        if not line.strip() or _ENUM_NON_MEMBER_RE.match(line):
            continue
        if not _ENUM_MEMBER_RE.match(line):
            raise SystemExit(
                f"{enum_name} enum in {proto_path} has a line this parser cannot "
                f"read as a member: {line.strip()!r}. Fix the parser rather than "
                "shipping a partial enum."
            )

    return {int(num): name for name, num in members}


